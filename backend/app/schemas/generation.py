from typing import List, Literal, Optional, Dict, Any
from pydantic import BaseModel, Field, field_validator


class HealthResponse(BaseModel):
    """Health check response schema."""
    status: str = "ok"
    service: str = "AI Video Generator Backend"
    device_info: Optional[Dict[str, Any]] = None


class ScenePlan(BaseModel):
    """Detailed scene plan for video generation."""
    scene_number: int = Field(..., description="Sequential scene index starting from 1")
    duration: int = Field(..., description="Scene duration in seconds")
    description: str = Field(..., description="Visual storyline description for the scene")
    video_prompt: str = Field(..., description="Detailed AI video generation prompt (subject, camera movement, lighting, atmosphere)")


class VideoPlan(BaseModel):
    """Structured video production plan generated by Qwen LLM."""
    title: str = Field(..., description="Title of the video")
    style: str = Field(..., description="Overall visual and cinematic style")
    total_duration: int = Field(..., description="Total requested duration in seconds")
    scenes: List[ScenePlan] = Field(..., description="List of sequential scene plans")
    voiceover: str = Field(..., description="Voiceover / narration script in target language")


class GenerateRequest(BaseModel):
    """Video generation request parameters schema."""
    prompt: str = Field(..., description="Description of the video to create")
    duration: Literal[10, 15, 20, 30] = Field(
        default=15,
        description="Duration of the video in seconds (10, 15, 20, 30)"
    )
    aspect_ratio: Literal["16:9", "9:16", "1:1"] = Field(
        default="16:9",
        description="Aspect ratio (16:9, 9:16, 1:1)"
    )
    language: Literal["English", "Hindi"] = Field(
        default="English",
        description="Voice narration language (English or Hindi)"
    )

    @field_validator("prompt")
    @classmethod
    def validate_prompt_not_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Prompt must not be empty.")
        return v.strip()


class GenerateResponse(BaseModel):
    """Response containing the structured video plan produced by Qwen LLM."""
    status: str = "success"
    message: str = "Structured video plan generated successfully using local Qwen2.5-1.5B-Instruct."
    request: GenerateRequest
    plan: VideoPlan
    device_info: Optional[Dict[str, Any]] = None
